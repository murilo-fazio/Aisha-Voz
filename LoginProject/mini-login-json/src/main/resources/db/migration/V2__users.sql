-- V2 — Usuarios no banco.
--
-- Substitui o arquivo local users.txt, que tinha tres problemas serios:
--   1. dentro do container vivia em /app/data sem volume, entao todo cadastro
--      desaparecia no restart;
--   2. o repositorio so sabia acrescentar linhas — nao havia como editar nem
--      excluir um usuario, o que tornava impossivel trocar uma senha;
--   3. o formato era CSV separado por ';' sem escape, entao um nome contendo
--      ';' corrompia o registro.
--
-- 'users' no plural porque 'user' e palavra reservada no Postgres.
-- ============================================================================

CREATE TABLE users (
    -- BY DEFAULT (e nao ALWAYS) para permitir insercao com id explicito, o que
    -- facilita carga de dados e testes sem abrir mao da sequencia automatica.
    id            BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          VARCHAR(120) NOT NULL,
    email         VARCHAR(255) NOT NULL,
    -- BCrypt gera sempre 60 caracteres; 72 da folga sem virar campo livre.
    password_hash VARCHAR(72)  NOT NULL,
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT now()
);

-- Unicidade sobre lower(email), e nao sobre email: o login sempre comparou
-- e-mail sem diferenciar maiusculas (equalsIgnoreCase). Um indice unico simples
-- deixaria "Ana@x.com" e "ana@x.com" coexistirem no banco e so um dos dois
-- conseguiria entrar. E o banco, e nao a aplicacao, que garante isso — a
-- checagem previa em Java tem corrida entre o SELECT e o INSERT.
CREATE UNIQUE INDEX ux_users_email_lower ON users (lower(email));
