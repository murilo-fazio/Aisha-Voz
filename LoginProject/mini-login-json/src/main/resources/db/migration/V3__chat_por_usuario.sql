-- ============================================================================
-- V3 — Conversas, mensagens e memoria por usuario.
--
-- Ate aqui o contexto da conversa era uma lista global dentro do processo
-- Python (global_context em app.py) e a memoria de longo prazo nao tinha dono.
-- Com mais de uma pessoa usando a plataforma ao mesmo tempo, o que um usuario
-- conversava entrava no prompt do outro. Era tambem o motivo de o gunicorn
-- rodar preso a um unico worker: mais de um processo quebraria a continuidade
-- desse estado em memoria.
--
-- Depois desta migracao o estado da conversa vive no banco, com dono.
-- ============================================================================

CREATE TABLE conversations (
    id         BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT       NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    -- Preenchido a partir da primeira mensagem do usuario; serve a lista de
    -- conversas na barra lateral (Fase 5).
    title      VARCHAR(200),
    -- Marca ate onde a conversa ja foi resumida. O contexto enviado ao modelo
    -- e formado apenas pelas mensagens POSTERIORES a esta, reproduzindo o
    -- comportamento antigo de limpar a lista logo apos gerar o resumo — so que
    -- agora por conversa, e nao para o processo inteiro.
    summarized_until_message_id BIGINT,
    created_at TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ  NOT NULL DEFAULT now()
);

-- Serve a lista "minhas conversas, mais recentes primeiro".
CREATE INDEX idx_conversations_user_recent
    ON conversations (user_id, updated_at DESC);

CREATE TABLE messages (
    id              BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id BIGINT      NOT NULL REFERENCES conversations (id) ON DELETE CASCADE,
    -- Mesmos nomes de papel usados pela API do modelo, para o Python montar o
    -- prompt sem traducao no meio.
    role            VARCHAR(16) NOT NULL,
    content         TEXT        NOT NULL,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ck_messages_role CHECK (role IN ('user', 'assistant'))
);

-- Le-se sempre "as mensagens desta conversa, em ordem" e "as posteriores a
-- um dado id"; o indice cobre os dois casos.
CREATE INDEX idx_messages_conversation
    ON messages (conversation_id, id);

-- ---------------------------------------------------------------------------
-- Memoria de longo prazo passa a ter dono.
--
-- As linhas existentes sao apagadas de proposito: foram gravadas quando a
-- memoria era global, portanto misturam o que pessoas diferentes conversaram e
-- nao ha como atribui-las a ninguem. Mante-las com um dono arbitrario
-- perpetuaria exatamente o vazamento que esta migracao existe para encerrar.
-- ---------------------------------------------------------------------------
DELETE FROM conversation_summaries;

ALTER TABLE conversation_summaries
    ADD COLUMN user_id BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE;

-- load_memory() passa a filtrar por usuario antes de ordenar por data.
DROP INDEX IF EXISTS idx_conversation_summaries_recent;
CREATE INDEX idx_conversation_summaries_user_recent
    ON conversation_summaries (user_id, created_at DESC, id DESC);
